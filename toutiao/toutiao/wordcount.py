"""头条号编辑器是怎么算字数的。

编辑器底部那行「共 N 字」**不是字符数**。2026-11-13 在后台实测，
它的口径是：

    字数 = 非 ASCII 字符数 + ⌈ASCII 字符数 / 2⌉

空白一律不计。

实测出来的探针（往正文末尾追加一段，看计数器涨多少）：

====================  ==========  ==========
追加的内容             原始字符     计数器增量
====================  ==========  ==========
``测试``               2          +2
``abcd``               4          +2
``12345678``           8          +4
`` ``（一个空格）        1          +0
``。``                 1          +1
====================  ==========  ==========

两处独立复核：

* 一个只含 ``【图1】`` 的短正文：非 ASCII 8 个 + ASCII 1 个 →
  ``8 + ⌈1/2⌉ = 9``，编辑器显示 9；
* 整篇正文：去空白后 2525 个字符（1318 个 ASCII + 1207 个非 ASCII）→
  ``1207 + ⌈659⌉ = 1866``，编辑器显示「共 1866 字」，逐字对上。

**为什么这件事要写进代码**：出包时我们按字符数算正文预算，平台按另一套
口径显示字数。两套口径混在一起，就分不清「我们写了 2717 个字符」和
「平台会显示 1866 字」是不是同一件事。

更要紧的是**平台按哪套口径判超限**：它对单段的「段落字数过多」告警也是
这一套——一段 216 个原始字符的中英混排段落（平台计 178 字）不告警，
一段 220 个纯汉字的段落（平台计 220 字）告警。
"""

from __future__ import annotations

import math
import re

__all__ = ["platform_word_count"]

_WHITESPACE = re.compile(r"\s")


def platform_word_count(text: str) -> int:
    """头条号编辑器会把这段文本显示成多少字。

    空白不计；ASCII 字符两个折算一个字，多出来的那半个也算一个
    （向上取整）。
    """
    stripped = _WHITESPACE.sub("", text)
    ascii_chars = sum(1 for char in stripped if ord(char) < 128)
    other_chars = len(stripped) - ascii_chars
    return other_chars + math.ceil(ascii_chars / 2)
